import { describe, it, expect } from 'vitest'
import { execFileSync } from 'node:child_process'
import { readFileSync } from 'node:fs'
import { formatRuby, formatThorRuby } from './ruby-formatter.js'

describe('Normale Ruby-Dateien', () => {
  it('formatiert Klassen und erhält mehrzeilige Argumente', async () => {
    const source = 'class Example\ndef create\nrender :index,\nformats: :html,\nstatus: :ok\nend\nend\n'
    const expected = 'class Example\n  def create\n    render :index,\n           formats: :html,\n           status: :ok\n  end\nend\n'

    expect(await formatRuby(source)).toBe(expected)
    expect(await formatRuby(expected)).toBe(expected)
  })

  it.each([
    'template="<% if enabled? %><%= title %><% end %>"\ntemplate\n',
    'template="<%= unfinished"\ntemplate\n',
    '# Example: <% if enabled? %>\ntext = <<~TEXT\n  Hallo <%= name %>  \n    weitere Zeile\nTEXT\ntext\n'
  ])('erhält den Wert von Strings und Heredocs mit ERB-Text: %s', async (source) => {
    const formatted = await formatRuby(source)
    const evaluate = input => execFileSync('ruby', ['-e', 'print Marshal.dump(eval(STDIN.read))'], { input })

    expect(evaluate(formatted)).toEqual(evaluate(source))
    expect(await formatRuby(formatted)).toBe(formatted)
  })

  it('formatiert den echten Tasks-Controller stabil und erzeugt gültiges Ruby', async () => {
    const source = readFileSync(new URL('./fixtures/tasks_controller.rb', import.meta.url), 'utf8')
    const formatted = await formatRuby(source)

    expect(formatted).toContain('redirect_to login_path,\n                alert: "Bitte melde dich an, um deine Aufgaben zu verwalten."')
    expect(await formatRuby(formatted)).toBe(formatted)
    expect(execFileSync('ruby', ['-c'], { input: formatted, encoding: 'utf8' })).toContain('Syntax OK')
  })

  it('wendet die Migrationsregel unabhängig von der eingestellten Zeilenlänge an', async () => {
    const source = 'add_column :users, :admin, :boolean, default: false, null: false\n'

    expect(await formatRuby(source, { printWidth: 200 })).toBe('add_column :users,\n           :admin,\n           :boolean,\n           default: false,\n           null: false\n')
  })

  it.each(['', '  \r\n\t\n'])('hält leere Ruby-Dateien leer: %j', async (source) => {
    expect(await formatRuby(source)).toBe('')
  })

  it('normalisiert Windows-Zeilenenden und berücksichtigt die Einrückungsbreite', async () => {
    const source = 'class Example\r\ndef index\r\nputs 1\r\nend\r\nend'

    expect(await formatRuby(source, { tabWidth: 4 })).toBe('class Example\n    def index\n        puts 1\n    end\nend\n')
  })

  it('weist ungültige Eingaben und Ruby-Syntax zurück', async () => {
    await expect(formatRuby(null)).rejects.toThrow(TypeError)
    await expect(formatRuby('class Broken\n')).rejects.toThrow('Ruby-Formatierung fehlgeschlagen')
    await expect(formatRuby('class <%= class_name %>\nend\n')).rejects.toThrow('Ruby-Formatierung fehlgeschlagen')
  })
})

describe('b4um Thor Ruby Formatter', () => {
  it('erhält Thor-Ausdrücke unverändert', async () => {
    const source = `class AddPositionTo<%= class_name.pluralize %> < ActiveRecord::Migration[8.0]
  def up
    add_column :<%= plural_table_name %>, :position, :integer
  end
end
`

    const result = await formatThorRuby(source)

    expect(result).toBe(source)
  })

  it('erhält Ruby-Strings mit Thor-Ausdrücken', async () => {
    const source = `self.table_name = "<%= plural_table_name %>"`

    expect(await formatThorRuby(source)).toBe(source.endsWith('\n') ? source : source + '\n')
  })

  it('verändert Ruby-Kommentare nicht', async () => {
    const source = `# frozen_string_literal: true
# Generated by b4um
`

    expect(await formatThorRuby(source)).toBe(source.endsWith('\n') ? source : source + '\n')
  })

  it('bleibt bei wiederholter Formatierung stabil', async () => {
    const source = `class Example
  def index
    puts "Hello"
  end
end
`

    const once = await formatThorRuby(source)
    const twice = await formatThorRuby(once)

    expect(twice).toBe(once)
  })

  it('weist ungültige Eingaben zurück', async () => {
    await expect(formatThorRuby(null)).rejects.toThrow(TypeError)
  })

  it.each(['', '  \r\n\t\n'])('fügt leeren Eingaben keine Leerzeile hinzu: %j', async (source) => {
    expect(await formatThorRuby(source)).toBe('')
  })

  it('normalisiert Windows-Zeilenenden und ergänzt den abschließenden Zeilenumbruch', async () => {
    const source = 'class <%= class_name %>\r\ndef index\r\nputs 1\r\nend\r\nend'

    expect(await formatThorRuby(source)).toBe('class <%= class_name %>\n  def index\n    puts 1\n  end\nend\n')
  })

  it('berücksichtigt die eingestellte Zeilenlänge', async () => {
    const source = 'values = [111, 222, 333]\n'

    expect(await formatThorRuby(source)).toBe(source)
    expect(await formatThorRuby(source, { printWidth: 20 })).toBe('values = [\n  111,\n  222,\n  333\n]\n')
  })

  it('berücksichtigt die eingestellte Einrückungsbreite', async () => {
    const source = 'class Task\ndef index\nputs 1\nend\nend\n'

    expect(await formatThorRuby(source, { tabWidth: 4 })).toBe('class Task\n    def index\n        puts 1\n    end\nend\n')
  })

  it('meldet eine fehlende Ruby-Executable mit Einrichtungshinweis', async () => {
    await expect(formatThorRuby('value = 1', { rubyExecutablePath: './missing-b4um-ruby' }))
      .rejects.toThrow('Ruby und die Gems syntax_tree sowie prettier_print müssen verfügbar sein.')
  })
})

